inline const uint8_t *statusGlyph(const char c) {
    const uint8_t uc = static_cast<uint8_t>(c);
    if (uc >= StandardASCIITableSize) {
        return nullptr;
    }

    uint8_t idx = StatusCharToIdx[uc];
    return (idx == InvalidIdx) ? nullptr : StatusGlyphsData[idx].data();
}

